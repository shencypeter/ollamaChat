import {mount} from '@vue/test-utils'
import {afterEach,expect,it} from 'vitest'
import RevisionHistoryList from './RevisionHistoryList.vue'
const options=[{id:'new',title:'#3',details:['2026/11/20 上午11:00:00']},{id:'middle',title:'#2',details:['2026/11/20 上午10:00:00']},{id:'old',title:'#1',details:['2026/11/20 上午9:00:00']}]
let wrappers=[]
function view(extra={}){const wrapper=mount(RevisionHistoryList,{attachTo:document.body,props:{options,modelValue:'middle',...extra}});wrappers.push(wrapper);return wrapper}
afterEach(()=>{wrappers.forEach(wrapper=>wrapper.unmount());wrappers=[]})
it('always shows a single flat list of numbered buttons with date subtitles',()=>{
 const v=view(),list=v.get('ul[aria-label="作答版本"]')
 expect(list.isVisible()).toBe(true);expect(list.findAll('button')).toHaveLength(3)
 expect(v.findAll('[data-round] strong').map(item=>item.text())).toEqual(['#3','#2','#1'])
 expect(v.findAll('[data-round] small').map(item=>item.text())).toEqual(options.map(item=>item.details[0]))
 expect(v.get('[data-round="middle"]').attributes('aria-current')).toBe('true')
 expect(v.get('[data-round="new"]').attributes('aria-current')).toBeUndefined()
 expect(v.find('[role="combobox"],[role="listbox"],[aria-expanded],select').exists()).toBe(false)
})
it('selects a revision without collapsing the list or duplicating its selected summary',async()=>{
 const v=view();await v.get('[data-round="new"]').trigger('click')
 expect(v.emitted('update:modelValue')).toEqual([['new']]);await v.setProps({modelValue:'new'})
 expect(v.get('[data-round="new"]').attributes('aria-current')).toBe('true')
 expect(v.findAll('[data-round]')).toHaveLength(3);expect(v.get('ul').isVisible()).toBe(true)
 expect(v.findAll('strong').map(item=>item.text())).toEqual(['#3','#2','#1'])
})
it('supports arrow and Home/End navigation with focus and selection on the same button',async()=>{
 const v=view();v.get('[data-round="middle"]').element.focus()
 await v.get('[data-round="middle"]').trigger('keydown',{key:'ArrowDown'})
 expect(v.emitted('update:modelValue').at(-1)).toEqual(['old']);expect(document.activeElement).toBe(v.get('[data-round="old"]').element)
 await v.get('[data-round="old"]').trigger('keydown',{key:'Home'})
 expect(v.emitted('update:modelValue').at(-1)).toEqual(['new']);expect(document.activeElement).toBe(v.get('[data-round="new"]').element)
 await v.get('[data-round="new"]').trigger('keydown',{key:'End'});expect(v.emitted('update:modelValue').at(-1)).toEqual(['old'])
 await v.get('[data-round="old"]').trigger('keydown',{key:'ArrowUp'});expect(v.emitted('update:modelValue').at(-1)).toEqual(['middle'])
})
it('disables all revision actions while busy without hiding their contents',async()=>{
 const v=view({disabled:true})
 for(const button of v.findAll('button')){expect(button.element.disabled).toBe(true);await button.trigger('click');await button.trigger('keydown',{key:'End'})}
 expect(v.emitted('update:modelValue')).toBeUndefined();expect(v.get('ul').isVisible()).toBe(true)
})
it('has one keyboard entry point and supports empty or missing selections honestly',async()=>{
 const v=view();expect(v.findAll('button[tabindex="0"]').map(item=>item.attributes('data-round'))).toEqual(['middle'])
 await v.setProps({modelValue:'missing'});expect(v.findAll('[aria-current]')).toHaveLength(0);expect(v.findAll('button[tabindex="0"]').map(item=>item.attributes('data-round'))).toEqual(['new'])
 await v.setProps({options:[]});expect(v.findAll('button')).toHaveLength(0)
})
it('does not mutate or renumber source options and safely renders text',async()=>{
 const source=[{id:'x',title:'#7',details:['<img src=x>']},{id:'y',title:'#2',details:['日期']}],original=JSON.stringify(source)
 const v=view({options:source,modelValue:'x'});await v.get('[data-round="y"]').trigger('click')
 expect(v.find('img').exists()).toBe(false);expect(v.text()).toContain('<img src=x>');expect(JSON.stringify(source)).toBe(original)
 expect(v.findAll('strong').map(item=>item.text())).toEqual(['#7','#2'])
})
it('shows a separate accessible remove action only for explicitly removable attempts',()=>{
 const v=view({options:[{...options[0],removable:true},{...options[1],removable:false},options[2]]})
 const remove=v.get('[data-remove-round="new"]')
 expect(remove.element.tagName).toBe('BUTTON');expect(remove.text()).toBe('×')
 expect(remove.attributes('aria-label')).toBe('將 #3 移至垃圾桶');expect(remove.attributes('title')).toBe('移至垃圾桶')
 expect(remove.element.parentElement).toBe(v.get('[data-round="new"]').element.parentElement)
 expect(v.find('[data-round] [data-remove-round]').exists()).toBe(false)
 expect(v.find('[data-remove-round="middle"]').exists()).toBe(false)
 expect(v.find('[data-remove-round="old"]').exists()).toBe(false)
})
it('requests removal without selecting a different attempt or changing the current row',async()=>{
 const v=view({options:options.map(option=>({...option,removable:true}))})
 await v.get('[data-remove-round="new"]').trigger('click')
 expect(v.emitted('remove')).toEqual([['new']]);expect(v.emitted('update:modelValue')).toBeUndefined()
 expect(v.get('[data-round="middle"]').attributes('aria-current')).toBe('true')
 expect(v.get('[data-round="new"]').attributes('aria-current')).toBeUndefined()
})
it('disables removal while busy and hides it when an attempt becomes protected',async()=>{
 const removableOptions=options.map(option=>({...option,removable:true})),v=view({options:removableOptions,disabled:true})
 const remove=v.get('[data-remove-round="new"]')
 expect(remove.element.disabled).toBe(true)
 remove.element.dispatchEvent(new MouseEvent('click',{bubbles:true}))
 expect(v.emitted('remove')).toBeUndefined();expect(v.emitted('update:modelValue')).toBeUndefined()
 await v.setProps({disabled:false,options:removableOptions.map(option=>({...option,removable:false}))})
 expect(v.find('[data-remove-round]').exists()).toBe(false)
})
it('keeps removal in the selected row Tab order and arrow navigation on selection buttons',async()=>{
 const v=view({options:options.map(option=>({...option,removable:true}))})
 expect(v.findAll('[data-remove-round][tabindex="0"]').map(item=>item.attributes('data-remove-round'))).toEqual(['middle'])
 await v.get('[data-round="middle"]').trigger('keydown',{key:'ArrowDown'})
 expect(document.activeElement).toBe(v.get('[data-round="old"]').element)
 expect(v.emitted('update:modelValue').at(-1)).toEqual(['old']);expect(v.emitted('remove')).toBeUndefined()
 await v.setProps({modelValue:'old'})
 expect(v.findAll('[data-remove-round][tabindex="0"]').map(item=>item.attributes('data-remove-round'))).toEqual(['old'])
 await v.get('[data-round="old"]').trigger('keydown',{key:'Home'})
 expect(document.activeElement).toBe(v.get('[data-round="new"]').element)
 await v.get('[data-round="new"]').trigger('keydown',{key:'End'})
 expect(document.activeElement).toBe(v.get('[data-round="old"]').element)
})
it('keeps a pending attempt selectable while its removal is disabled',async()=>{
 const v=view({options:[{...options[0],removable:true,removeDisabled:true},...options.slice(1)]})
 const remove=v.get('[data-remove-round="new"]')
 expect(remove.element.disabled).toBe(true);expect(v.get('[data-round="new"]').element.disabled).toBe(false)
 remove.element.dispatchEvent(new MouseEvent('click',{bubbles:true}))
 expect(v.emitted('remove')).toBeUndefined()
 await v.get('[data-round="new"]').trigger('click')
 expect(v.emitted('update:modelValue')).toEqual([['new']])
 await v.setProps({options:[{...options[0],removable:true,removeDisabled:false},...options.slice(1)]})
 expect(v.get('[data-remove-round="new"]').element.disabled).toBe(false)
 await v.get('[data-remove-round="new"]').trigger('click');expect(v.emitted('remove')).toEqual([['new']])
})
